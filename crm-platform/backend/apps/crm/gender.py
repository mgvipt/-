# -*- coding: utf-8 -*-
"""Визначення статі контрагента за іменем. Без ШІ — правила + словник винятків.

Порядок надійності:
1. По батькові (-ович / -івна) — майже 100%
2. Імʼя — словник винятків + закінчення (-а/-я = жіноче)
3. Прізвище (-ов/-ова, -ський/-ська) — лише якщо імені нема

Якщо імʼя не схоже на справжнє (нік з латиниці/цифр) — стать НЕ ставимо.
"""
import re

# Чоловічі імена, що закінчуються на голосну (інакше правило «-а/-я = жінка» їх зламає)
MALE_EXCEPTIONS = {
    "микита", "нікіта", "никита", "ілля", "илья", "кузьма", "лука", "сава", "хома", "фома",
    "петро", "павло", "дмитро", "данило", "данила", "михайло", "гаврило", "марко", "левко",
    "тодось", "остап", "сила", "юра", "саша", "женя", "валера", "діма", "дима", "вова",
    "льоша", "лёша", "толя", "коля", "костя", "сєва", "сева", "гриша", "миша", "паша",
    "серьога", "сєрьога", "андрюха", "ваня", "боря", "гена", "слава", "стёпа", "стьопа",
    "яша", "жора", "тёма", "тьома", "артём", "артем", "сімба",
}

# Жіночі імена, що закінчуються на приголосну
FEMALE_EXCEPTIONS = {
    "любов", "любовь", "нінель", "нинель", "аделаїд", "естер", "рут", "суламіф",
    "ізабель", "изабель", "мішель", "мишель", "ніколь", "николь", "керол", "джен",
}

_CYR = re.compile(r"^[а-яёіїєґА-ЯЁІЇЄҐ'\-\s]{2,}$")


def _norm(x):
    return (x or "").strip().lower().replace("ё", "е")


def _by_middle(mid):
    """По батькові — найнадійніше."""
    m = _norm(mid)
    if not m or not _CYR.match(m):
        return ""
    if m.endswith(("івна", "ївна", "овна", "евна", "ична", "інічна", "инична")):
        return "f"
    if m.endswith(("ович", "йович", "евич", "ич")):
        return "m"
    return ""


def _by_last(last):
    """Прізвище. -ко/-ук/-юк/-енко — нейтральні, їх пропускаємо."""
    l = _norm(last)
    if not l or not _CYR.match(l):
        return ""
    # ВАЖЛИВО: -ин/-ін/-ишин (Процишин, Романишин, Русин) в українській ОДНАКОВІ
    # у чоловіків і жінок — їх НЕ використовуємо. Тільки однозначні пари.
    if l.endswith(("ська", "цька", "ова", "єва", "ева")):
        return "f"
    if l.endswith(("ський", "цький", "ов", "єв", "ев")):
        return "m"
    return ""


def _by_first(first):
    f = _norm(first)
    if not f or not _CYR.match(f):
        return ""
    f = f.split()[0]
    if f in MALE_EXCEPTIONS:
        return "m"
    if f in FEMALE_EXCEPTIONS:
        return "f"
    if f.endswith(("а", "я")):
        return "f"
    return "m"


def detect_gender(first_name="", middle_name="", last_name=""):
    """Повертає ('m'|'f'|'', джерело). Порожньо = не визначили (нік, латиниця, порожньо)."""
    g = _by_middle(middle_name)
    if g:
        return g, "по батькові"
    g = _by_first(first_name)          # імʼя надійніше за прізвище (Ірина Процишин!)
    if g:
        return g, "імʼя"
    g = _by_last(last_name)            # лише як запасний варіант (порожнє/латинське імʼя)
    if g:
        return g, "прізвище"
    return "", ""
