def tools_offer(lines):
    return 'Дякуємо за оплату! 💚 Ваш тест-набір вже готуємо.\n\nПідкажіть, чи є у вас інструменти для нанесення? Для Galateya та шовків потрібні пензель-макловиця і пензель для декору — з ними малюнок виходить як у дизайнерських інтерʼєрах, і вони знадобляться для основного обʼєму.\n\nМожемо додати до вашої відправки, щоб все приїхало разом:\n' + lines + '\n\nНапишіть номери — додамо 😊'


def receipt_message(body, url):
    return "%s\n\n🧾 %s" % (body, url)


def ttn_created(ttn, cod=0):
    text = "Для вашого замовлення створено ТТН Нової Пошти! 📦\nНомер ТТН: %s\nВідстежити: https://novaposhta.ua/tracking/?cargo_number=%s" % (ttn, ttn)
    if cod:
        text += "\nДо сплати при отриманні: %s грн" % int(cod)
    return text


def tools_products():
    from apps.integrations.models import IntegrationSettings
    from apps.warehouse.models import Product
    st = IntegrationSettings.objects.filter(provider="upsell_test_kit").first()
    if st and not st.is_active:
        return []
    ids = ((st.config or {}) if st else {}).get("product_ids") or []
    order = {pid: i for i, pid in enumerate(ids)}
    return sorted(Product.objects.filter(id__in=ids, is_active=True), key=lambda p: order.get(p.id, 99))


def tools_lines(prods):
    return "\n".join("%d. %s — %d грн" % (i + 1, p.name, round(float(p.price))) for i, p in enumerate(prods))


