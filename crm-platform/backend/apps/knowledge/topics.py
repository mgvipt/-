def guess_topic(text):
    t = (text or "").lower()
    for topic, rx in TOPIC_HINTS:
        if re.search(rx, t):
            return topic
    return "other"


def guess_topics(text):
    t = (text or "").lower()
    return {topic for topic, rx in TOPIC_HINTS if re.search(rx, t)}


def flags_for(text):
    t = (text or "").lower()
    return [msg for rx, msg in FLAGS if re.search(rx, t)]
