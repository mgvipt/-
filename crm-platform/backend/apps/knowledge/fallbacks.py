def compose_style():
    """Системний текст помічника ✨ (стабільний — працює кеш): персона + теми з бази (затверджене)
    або вбудований текст. Від розмови не залежить."""
    try:
        from .reader import approved_for, merge_with_fallback, render_items
        body = merge_with_fallback("compose_assist", COMPOSE_CHUNKS, query=None, limit=0, with_prices=False)
        rules = [i for i in approved_for("compose_assist")
                 if i.kind == "rule" and i.topic not in {t for t, _ in COMPOSE_CHUNKS if t}]
        if rules:
            body += "\n\n[З бази знань — правила]\n" + render_items(rules, 3000)
    except Exception:
        from .catalog import render
        body = "\n\n".join(render(c).strip() for _, c in COMPOSE_CHUNKS)
    return COMPOSE_PERSONA + body


def compose_extra(query=None):
    """Змінна частина для ✨ (у запит, не в системний текст): затверджені записи інших тем, що стосуються розмови.
    Порожня база → порожньо (запит такий самий, як раніше)."""
    try:
        from .reader import approved_for, render_items, select
        fallback_topics = {t for t, _ in COMPOSE_CHUNKS if t}
        items = [i for i in select("compose_assist", query, 10, items=approved_for("compose_assist"))
                 if i.kind != "rule" and i.topic not in fallback_topics]
        txt = render_items(items, 4000) if items else ""
    except Exception:
        txt = ""
    return ("\n\nДОВІДКА З БАЗИ ЗНАНЬ WALLCOV (затверджено Олегом; лише для перевірки фактів, нічого не додавай від себе):\n" + txt) if txt else ""
